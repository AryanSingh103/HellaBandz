"""Render docs/PERFORMANCE.md from benchmarks/results/*.json (Lucera performance-report template)."""

from __future__ import annotations

import json
import hashlib
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "benchmarks/results"


def load(name: str) -> dict | None:
    p = R / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else None


def med(d: dict, k: str) -> float:
    return d[k]["median"]


def env_block(env: dict) -> str:
    return (f"- Host: {env.get('host_cpu', '?')}, {env.get('host_ncpu', '?')} cores, "
            f"{env.get('host_mem_gb', 0):.0f} GiB RAM, {env.get('platform', '?')}\n"
            f"- Docker VM: {env.get('docker_vm_ncpu', '?')} vCPU, {env.get('docker_vm_mem_gb', '?')} GiB, "
            f"Docker {env.get('docker_server', '?')}\n"
            f"- Python {env.get('python')} (CPython), measured {env.get('captured_at')}\n"
            f"- Source SHA-256: `{env.get('source_sha256', '?')}`; checkout `{env.get('git_revision', '?')}` "
            "(the source hash excludes generated results and docs)")


def main() -> None:
    e, d, rc = load("engine"), load("db_throughput"), load("recovery")
    blocks = [b for b in (e, d, rc) if b]
    hashes = {b["environment"].get("source_sha256") for b in blocks}
    sources = sorted([*ROOT.glob("quantswarm/**/*.py"), *ROOT.glob("quantswarm/**/*.sql"),
                      *ROOT.glob("benchmarks/*.py"), ROOT / "Dockerfile", ROOT / "docker-compose.yml",
                      ROOT / "pyproject.toml", ROOT / "uv.lock"])
    current = hashlib.sha256()
    for path in sources:
        current.update(path.relative_to(ROOT).as_posix().encode() + b"\0" + path.read_bytes().replace(b"\r\n", b"\n"))
    if len(blocks) != 3 or hashes != {current.hexdigest()}:
        raise RuntimeError("benchmark results are stale or measure different source trees; rerun make bench")
    if d and not all(r["verify_match"] for r in d["runs"]):
        raise RuntimeError("durable benchmark failed independent verification")
    if rc and not all(r["verify_match"] for r in rc["runs"]):
        raise RuntimeError("recovery benchmark failed independent verification")
    out = ["# Performance\n",
           "All numbers below are generated by `benchmarks/report.py` from the JSON files in `benchmarks/results/`. "
           "Re-run with `make bench`. LLM latency and data-download time are never included. Every DB-backed run "
           "ends with an independent replay (`/v1/verify`) and is only counted if the digests match.\n"]
    out.append("Operator authentication and the transactional 16-table audit journal are enabled in the durable path. "
               "The periodic Solana signer is stopped for this benchmark to isolate order-path throughput; "
               "sealing and full-trace verification are checked separately. Journal write/storage overhead is included.\n")
    if e and e.get("binance_snapshot"):
        snapshot = e["binance_snapshot"]
        out.append(f"Real-data workload: `{snapshot['dataset_id']}` ({snapshot['unit_version']}), "
                   f"content SHA-256 `{snapshot['content_sha256']}`. Legacy snapshots are preserved and excluded.\n")

    # ------------------------------------------------------------------ headline
    if d:
        runs = [r for r in d["runs"] if not r["warmup"]]
        def agg(bs, c, key):
            xs = [r for r in runs if r["batch_size"] == bs and r["concurrency"] == c]
            return statistics.median(key(r) for r in xs) if xs else None
        best = max((r for r in runs if r["batch_size"] == 64), key=lambda r: r["orders_per_s"])
        out.append("## Headline\n")
        out.append(f"- **Pre-trade risk check:** p50 {med(e['risk_check_latency_us']['summary'], 'p50'):.1f} µs, "
                   f"p99 {med(e['risk_check_latency_us']['summary'], 'p99'):.1f} µs (in-process)." if e else "")
        out.append(f"- **Durable order path** (HTTP → Postgres command log → worker → atomic ledger commit → response), "
                   f"1 vCPU worker + 1 vCPU API + 2 vCPU DB: **{agg(64, 50, lambda r: r['orders_per_s']):.0f} orders/s** "
                   f"at 50 concurrent clients (p99 {agg(64, 50, lambda r: r['latency_ms']['p99']):.0f} ms); "
                   f"{agg(64, 1, lambda r: r['latency_ms']['p50']):.1f} ms p50 for a single client.")
        if rc:
            big = max((r for r in rc["runs"] if r["mode"] == "checkpoint"), key=lambda r: r["events"])
            out.append(f"- **Crash recovery:** {big['events']:,}-event ledger restored from checkpoint + "
                       f"{big['replayed_events']:,}-event verified suffix in "
                       f"{med(big['in_process'], 'total_s'):.2f} s; container restart to ready "
                       f"{med(big['container_restart'], 'container_start_to_ready_s'):.1f} s.")
        if e:
            b = e["replay"].get("binance_btcusdt_131k_bars")
            if b:
                out.append(f"- **Replay:** {b['bars']:,} real Binance 1-minute bars backtested at "
                           f"{med(b['backtest'], 'bars_per_s'):,.0f} bars/s; event-log replay "
                           f"{b['event_log_replay_events_per_s']:,.0f} events/s.")
        out.append("")

    # ------------------------------------------------------------------ environment
    out.append("## 1. Environment\n")
    env = (d or e or rc or {}).get("environment", {})
    out.append(env_block(env))
    out.append("- Container limits (docker-compose.yml): TimescaleDB 2.17.2-pg16 **2 vCPU / 2 GiB** "
               "(`shared_buffers=256MB`, default fsync and synchronous_commit); execution worker **1 vCPU / 512 MiB**; "
               "API (uvicorn, single process) **1 vCPU / 512 MiB**; load client **1 vCPU / 512 MiB** inside the compose "
               "network (no host port-forwarding in the measured path).")
    out.append("- In-process benchmarks run on the host Python 3.12 without container limits (single thread). "
               "Worker, API and load-client images use CPython 3.12.13 (Dockerfile).\n")

    # ------------------------------------------------------------------ engine
    if e:
        rk, cl = e["risk_check_latency_us"], e["command_latency_us"]
        out.append("## 2. Pre-trade risk check and command latency (in-process)\n")
        out.append(f"**Workload.** {rk['workload']}. 3 warm-up + 5 measured passes; the table shows the median "
                   "across passes (min–max in brackets).\n")
        out.append("| Metric | p50 | p95 | p99 | p99.9 | max |\n|---|---|---|---|---|---|")
        for label, blk in (("`evaluate_order` (risk only), µs", rk), ("`process` (risk + event + SHA-256 chain), µs", cl)):
            s = blk["summary"]
            out.append(f"| {label} | " + " | ".join(
                f"{s[k]['median']:.1f} [{s[k]['min']:.1f}–{s[k]['max']:.1f}]" for k in ("p50", "p95", "p99", "p999", "max"))
                       + " |")
        out.append(f"\n`process` workload: {cl['workload']}. Throughput {med(cl['summary'], 'commands_per_s'):,.0f} "
                   f"commands/s single-threaded; a 5-symbol bar (fills + expiry + mark) costs "
                   f"{med(cl['summary'], 'bar_p50_us'):.0f} µs p50.\n")
        out.append("**Why it matters.** This is the cost the deterministic core adds per decision, separate from "
                   "I/O. It sets the ceiling a single-writer worker could reach with free storage.\n")
        out.append("**Procedure.** `uv run python benchmarks/run_benchmarks.py engine`\n")
        out.append("### Working-order scaling\n")
        out.append("Same proposals and fixed positions; 3 warm-up + 5 measured passes per size. "
                   "Only open buys grow. Exposure and reservation lookups are O(1) per agent; "
                   "marking positions still costs O(positions).\n")
        out.append("| Working orders | Risk p50 µs | Risk p99 µs |\n|---|---|---|")
        for row in e["risk_check_open_order_scaling"]:
            out.append(f"| {row['open_orders']:,} | {med(row['summary'], 'p50'):.1f} | {med(row['summary'], 'p99'):.1f} |")
        out.append("")

        out.append("## 3. Historical replay / backtest speed (in-process)\n")
        out.append("| Dataset | Bars | Symbols | Backtest bars/s | Ledger events/s | Event-log replay events/s |\n|---|---|---|---|---|---|")
        for name, v in e["replay"].items():
            out.append(f"| {name} | {v['bars']:,} | {v['symbols']} | {med(v['backtest'], 'bars_per_s'):,.0f} | "
                       f"{med(v['backtest'], 'events_per_s'):,.0f} | {v['event_log_replay_events_per_s']:,.0f} |")
        out.append(f"\nData loading (Parquet + hash verification) is measured separately: synthetic "
                   f"{e['synthetic_load_s'] * 1000:.0f} ms" + (f", Binance {e['binance_load_s'] * 1000:.0f} ms"
                                                              if 'binance_load_s' in e else "") +
                   ". Download time is excluded (Binance: `scripts/ingest_binance.py` reports it).\n")
        out.append("**Workload.** SMA(20/100) crossover on every symbol, sized so orders fill. "
                   "Synthetic data is committed; Binance BTCUSDT 1-minute klines Jan–Mar 2024 "
                   "(checksummed public archive) are included when downloaded. 1 warm-up + 3 runs, median.\n")
        out.append("**Procedure.** `uv run python scripts/ingest_binance.py && uv run python benchmarks/run_benchmarks.py engine`\n")

    # ------------------------------------------------------------------ db
    if d:
        out.append("## 4. Durable order throughput and latency (API + worker + TimescaleDB)\n")
        out.append(f"**Workload.** {d['workload']}. A new 5-symbol bar is published every 200 orders so working "
                   "orders fill and close as in a session (bar requests are not counted as orders). Fresh "
                   "portfolio and fresh worker container per run; 1 warm-up + 3 measured runs per cell; median shown.\n")
        out.append("| Worker batch size | Clients | Orders/s | p50 ms | p95 ms | p99 ms | max ms | verify |\n|---|---|---|---|---|---|---|---|")
        runs = [r for r in d["runs"] if not r["warmup"]]
        cells = sorted({(r["batch_size"], r["concurrency"]) for r in runs}, key=lambda x: (-x[0], x[1]))
        for bs, c in cells:
            xs = [r for r in runs if r["batch_size"] == bs and r["concurrency"] == c]
            m = lambda f: statistics.median(f(r) for r in xs)  # noqa: E731
            out.append(f"| {bs} | {c} | {m(lambda r: r['orders_per_s']):,.0f} | {m(lambda r: r['latency_ms']['p50']):.1f} | "
                       f"{m(lambda r: r['latency_ms']['p95']):.1f} | {m(lambda r: r['latency_ms']['p99']):.1f} | "
                       f"{m(lambda r: r['latency_ms']['max']):.0f} | {'all match' if all(r['verify_match'] for r in xs) else 'MISMATCH'} |")
        st: dict = {}
        for r in runs:
            for k, v in r["statuses"].items():
                st[k] = st.get(k, 0) + v
        out.append(f"\nResponse mix across measured runs: {json.dumps(st)} (duplicates return the original decision; "
                   "invalid orders are rejected by R6 and still recorded).\n")
        out.append("**Procedure.** `docker compose up -d --build db api && docker compose --profile bench build bench && "
                   "uv run python benchmarks/run_benchmarks.py db` (starts one resource-limited worker container per run).\n")

    if rc:
        out.append("## 5. Recovery time vs ledger size\n")
        out.append(f"Dataset: `{rc['dataset']}`; {rc['source_events']:,} source events. "
                   f"Requested sizes unavailable on this dataset: {rc['unavailable_sizes']}.\n")
        out.append("**Workload.** Event logs produced by the real engine (SMA strategy over the 131k-bar Binance BTCUSDT snapshot; the synthetic fixture if absent), "
                   "loaded into `ledger_events` with a matching projection. Compare full replay to checkpoint recovery "
                   "(interval 10,000 events). Checkpoints contain the complete state and retry decisions; startup "
                   "checks snapshot hash, economic digest, ledger anchor and suffix chain, then the final projection digest. "
                   "Each result is compared with an independent full replay. Requested sizes and checkpoints are rounded "
                   "down to complete command boundaries. Sizes near 105,000 exercise a roughly 5,000-event suffix; "
                   "exact checkpoint boundaries have an empty suffix. Production writes checkpoints at complete batch boundaries.\n")
        out.append("| Events | Mode | Replayed suffix | Load s | Replay + verify s | Total s | Container start → ready s |\n|---|---|---|---|---|---|---|")
        for r in rc["runs"]:
            ip, cr = r["in_process"], r["container_restart"]
            out.append(f"| {r['events']:,} | {r['mode']} | {r['replayed_events']:,} | {med(ip, 'load_s'):.3f} | {med(ip, 'replay_s'):.3f} | {med(ip, 'total_s'):.3f} | "
                       f"{med(cr, 'container_start_to_ready_s'):.2f} |")
        out.append("\n**Procedure.** `uv run python benchmarks/run_benchmarks.py recovery` (in-process: 1 warm-up + 3; "
                   "container: 3 cold starts of the 1 vCPU worker image, timed until its recovery telemetry row appears).\n")

    out.append(INTERPRETATION)
    (ROOT / "docs/PERFORMANCE.md").write_text("\n".join(x for x in out if x is not None) + "\n", encoding="utf-8")
    print("wrote docs/PERFORMANCE.md")


INTERPRETATION = """## 6. Interpretation, bottlenecks and tradeoffs

**Where the time goes.** The in-process engine needs only tens of microseconds per command, while the
durable path costs milliseconds per order. Nearly all of that is I/O: the HTTP hop, an autocommitted insert
into the command log, the worker's transaction (events + projections + digest + `NOTIFY`), a WAL flush, and
the response lookup. With one client the system is latency-bound (one order per round-trip). With more
clients the worker drains several commands per transaction (group commit), which spreads the fsync and
projection costs over more orders.

**Batching tradeoff.** Batch size 1 commits every command separately (smallest blast radius, most fsyncs);
batch 64 amortizes the commit. Atomicity still holds per batch: a crash rolls back the whole batch, and it is
re-processed deterministically after restart (`tests/recovery`).

**Next throughput limit.** The single-writer design caps each portfolio. The latency/throughput tables
alone do not establish which process saturates first; that requires CPU and I/O profiling. Shard independent
portfolios across workers before changing the ordering model within one portfolio.

**Earlier development observations (historical, not re-measured on this host):**
1. *Postgres `NOTIFY` serializes commits.* `NOTIFY` takes a global lock at commit time. Notifying inside every
   command insert made concurrent inserts queue behind each other. The API now coalesces worker wake-ups
   through one task.
2. *O(state) work per commit.* The first version hashed the full state, including the idempotency table, on
   every commit. In a workload where orders never filled, throughput fell to about 20 orders/s as working
   orders piled up. The digest now excludes the idempotency table (the event hash chain already covers it),
   and the workload publishes bars so orders fill as they would in real use.
3. *The load generator was the bottleneck.* An httpx-based client topped out near 250 req/s at 50
   connections with both API and DB idle. Switching to aiohttp inside the compose network raised measured
   throughput about 5x. Throughput numbers are only trustworthy after confirming that the system under test
   is the thing saturating.

**What would fail or need redesign next.**
- Per-agent cost exposure and buy reservations are maintained in O(1) per event. Risk checks still mark
  positions; bar fills scan working orders. Invariant checks and projection hashing still scan state per batch.
- Recovery replays only a suffix, but loading and validating a checkpoint grows with positions, working orders
  and retained retry decisions. Full-history `/v1/verify` is still linear and is required to detect tampering
  in the trusted checkpoint prefix. SHA-256 checks detect accidental corruption, not an attacker who can
  rewrite the database and recompute all hashes. Checkpoint creation adds periodic serialization/commit cost.
- The `commands` and `ledger_events` tables grow without bound. Fix: partition or archive by portfolio and time
  (both could become hypertables keyed by `received_at` / `created_at`).
- If one portfolio needs far more than a few thousand orders/s, move the ledger to an in-memory single-writer
  engine with its own write-ahead log, and keep Postgres for projections and analytics.
"""


if __name__ == "__main__":
    main()
